def generate_dataset_csv():
    records = []
    rec_id = 1

    for title, text, category, source_type in REAL_SAMPLES:
        records.append({
            "id": f"TL-REAL-{rec_id:04d}",
            "title": title,
            "text": text,
            "label": "REAL",
            "target": 0,
            "category": category,
            "source_type": source_type
        })
        rec_id += 1

    fake_id = 1
    for title, text, category, source_type in FAKE_SAMPLES:
        records.append({
            "id": f"TL-FAKE-{fake_id:04d}",
            "title": title,
            "text": text,
            "label": "FAKE",
            "target": 1,
            "category": category,
            "source_type": source_type
        })
        fake_id += 1

    fieldnames = ["id", "title", "text", "label", "target", "category", "source_type"]
    PRIMARY_DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)
    SECONDARY_DATASET_PATH.parent.mkdir(parents=True, exist_ok=True)

    for p in [PRIMARY_DATASET_PATH, SECONDARY_DATASET_PATH]:
        with open(p, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(records)

    print(f"Dataset successfully generated at {PRIMARY_DATASET_PATH} and {SECONDARY_DATASET_PATH}")
    print(f"Total samples: {len(records)} (REAL: {len(REAL_SAMPLES)}, FAKE: {len(FAKE_SAMPLES)})")
    return PRIMARY_DATASET_PATH

if __name__ == "__main__":
    generate_dataset_csv()
